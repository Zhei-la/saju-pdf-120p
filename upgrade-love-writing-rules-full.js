const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `[챕터별 작성 방식]`;

const rules = `[챕터별 작성 방식]
- 이 챕터는 제목에 맞는 관점 하나만 깊게 다루세요.
- 모든 챕터를 "상대 반응에 민감함 / 혼자 고민함 / 감정 숨김 / 안정 추구 / 배려형 / 신중함"으로 귀결하지 마세요.
- 이미 다른 챕터에서 다룬 성향은 반복하지 마세요.
- 같은 성격 설명을 다른 말로 바꿔 반복하지 마세요.

[챕터별 역할 분리]
- 썸 파트는 행동 패턴 중심으로 작성하세요.
- 연락 파트는 심리 흐름 중심으로 작성하세요.
- 재회 파트는 감정 잔존감과 다시 흔들리는 포인트 중심으로 작성하세요.
- 갈등 파트는 말투, 침묵, 거리감, 자존심 중심으로 작성하세요.
- 안정기/장기 관계 파트는 편안함, 신뢰, 오래 가는 조건 중심으로 작성하세요.
- 잘 맞는 상대 유형 파트는 상대의 태도와 관계 유지 방식 중심으로 작성하세요.
- 총평 파트는 반복 요약이 아니라 앞으로의 감정 흐름과 핵심 변화 중심으로 작성하세요.

[추상어 금지 및 행동 장면 전환]
- "상대 반응에 민감합니다"라고만 쓰지 말고, 답장이 늦거나 말투가 달라졌을 때 어떤 행동을 하는지 장면으로 보여주세요.
- "감정을 숨깁니다"라고만 쓰지 말고, 좋아할수록 말투·답장·거리감이 어떻게 달라지는지 보여주세요.
- "안정감을 원합니다"라고만 쓰지 말고, 어떤 태도에 마음이 열리고 어떤 태도에 닫히는지 보여주세요.
- "혼자 고민합니다"라고만 쓰지 말고, 카톡 창을 다시 열어보거나 상대 말을 곱씹는 식의 실제 행동으로 표현하세요.
- 반드시 실제 연애 장면을 넣으세요: 읽씹, 답장 텐션 변화, 썸의 애매함, 싸운 뒤 침묵, 거리두기, 재회 직전, 갑작스러운 연락, 상대 말투 변화 중 최소 하나.

[소름 디테일 강화]
- 독자가 "와, 이거 내 얘기다"라고 느낄 수 있는 생활 디테일을 포함하세요.
- 예시 표현을 그대로 반복하지 말고 상황에 맞게 변형하세요.
- 좋아할수록 오히려 말과 행동을 조심하는 장면.
- 답장이 늦으면 괜찮은 척하지만 계속 확인하는 장면.
- 상대 말투가 달라지면 하루 기분이 영향을 받는 장면.
- 먼저 표현했다가 상처받을까 봐 타이밍을 재는 장면.
- 감정이 커질수록 표현보다 관찰이 먼저 나오는 장면.
- 상대의 작은 반응 변화에도 분위기를 읽으려는 장면.

[문장 리듬 다양화]
- "~하는 편입니다", "~할 수 있습니다", "~경향이 있습니다", "~도움이 됩니다" 같은 문장 끝을 반복하지 마세요.
- 짧은 문장, 긴 문장, 감정형 문장을 섞으세요.
- 한 문단 전체가 설명형 문장으로만 이어지지 않게 하세요.
- 중간중간 짧고 강한 문장을 넣으세요.
- 예: "좋아할수록 더 침착한 척하게 됩니다."
- 예: "확신이 없으면 마음보다 눈치를 먼저 봅니다."
- 예: "상처받을까 봐 먼저 다가가지 못하는 순간이 있습니다."
- 질문형 문장을 가끔 사용해도 됩니다. 단, 과하게 쓰지 마세요.

[챕터별 감정 온도]
- 썸: 설렘, 긴장감, 기대감, 애매함.
- 연락: 초조함, 확인 욕구, 말투 변화, 기다림.
- 재회: 미련, 흔들림, 다시 이어질 가능성.
- 갈등: 거리감, 답답함, 침묵, 자존심.
- 안정기: 편안함, 신뢰, 오래 가는 조건.
- 총평: 여운, 방향성, 앞으로의 감정 변화.

[감정 몰입 요소]
- 상대가 이 사람을 어떻게 느낄 가능성이 있는지 포함하세요.
- 관계가 가까워지는 시기, 흔들리는 시기, 연락운이 살아나는 시기를 자연스럽게 넣으세요.
- 갑자기 가까워질 가능성, 다시 연락이 이어질 흐름, 상대가 흔들릴 수 있는 포인트를 상황에 맞게 넣으세요.
- 운세 리포트답게 미래 흐름이 느껴지게 작성하세요.

[마무리 방식]
- 각 챕터의 마지막 문장은 조언보다 여운이 남는 문장으로 끝내세요.
- "중요합니다", "필요합니다", "도움이 됩니다"로 끝나는 마무리를 반복하지 마세요.
- 마지막 문장은 감정의 방향이나 관계의 여지를 남기세요.`;

if (s.includes(marker)) {
  s = s.replace(/\[챕터별 작성 방식\][\s\S]*?\$\{prompt\}/, rules + `

\${prompt}`);
} else {
  s = s.replace(
    `분석 항목: \${title}
━━━━━━━━━━━━━━━━━━`,
    `분석 항목: \${title}
━━━━━━━━━━━━━━━━━━

${rules}`
  );
}

fs.writeFileSync(file, s, 'utf8');
console.log('fully upgraded love writing rules without omissions');
