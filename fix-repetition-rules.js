const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const rule = `
중요한 작성 원칙:
- 사주 원국 설명은 리포트 초반 또는 PART 첫 장에서만 정리하세요.
- 각 챕터마다 갑목, 오행, 신약, 수기운 부족, 식신, 편재, 정재 설명을 반복하지 마세요.
- 각 챕터 첫 문장을 "일간이", "갑목은", "오행 분포를 보면", "사주 구조상"으로 시작하지 마세요.
- 본문은 명리학 설명서가 아니라 실제 상담처럼 작성하세요.
- 독자가 궁금해하는 것은 이론이 아니라 실제 행동, 감정 변화, 관계 패턴입니다.
- 같은 결론을 반복하지 말고, 각 챕터마다 새로운 이야기를 하세요.
- 용어 해설은 전체 리포트에서 꼭 필요한 경우에만 1~2회 짧게 사용하세요.
- [용어 해설]을 매 챕터 자동으로 붙이지 마세요.
- "중요합니다", "필요합니다", "가능성이 있습니다", "나타납니다", "의미합니다"를 반복하지 마세요.
`;

if (!s.includes('사주 원국 설명은 리포트 초반 또는 PART 첫 장에서만 정리하세요.')) {
  s = s.replace(
    '이론 설명보다 실제 관계 흐름과 행동 패턴 묘사를 우선하세요.',
    '이론 설명보다 실제 관계 흐름과 행동 패턴 묘사를 우선하세요.\n\n' + rule
  );
}

s = s.replace(
  /- 위 사주 원국의 구체적인 정보\(일간, 월지, 오행, 십성, 용신 등\)를 반드시 언급하며 해석/g,
  '- 사주 원국 정보는 초반 요약에서만 충분히 설명하고, 각 챕터에서는 필요한 경우에만 짧게 언급'
);

s = s.replace(
  /- \[용어 해설\][\s\S]*?같은 용어 해설을 매 챕터 반복하지 말 것/g,
  '- [용어 해설]은 전체 리포트에서 꼭 필요한 경우에만 1~2회 짧게 사용\n- 같은 용어 해설을 매 챕터 반복하지 말 것'
);

s = s.replace(
  /- 같은 사주 용어 반복 금지/g,
  '- 같은 사주 용어 반복 금지\n- 갑목, 신약, 수기운 부족, 오행, 식신, 편재, 정재 반복 금지'
);

s = s.replace(
  /- 실제 연애 상황 예시 포함/g,
  '- 실제 연애 상황 예시 포함\n- 연락, 읽씹, 썸, 질투, 거리두기, 재회, 소비습관, 직장갈등처럼 현실 장면 중심으로 작성'
);

fs.writeFileSync(file, s, 'utf8');
console.log('anti repetition rules added');
