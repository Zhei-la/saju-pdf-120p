const fs = require('fs');

const file = 'services/consultant.js';
let s = fs.readFileSync(file, 'utf8');

s = s.replace(
/가장 중요한 원칙은 사용자가 선택한 PDF 리포트 내용과 일치하게 답변하는 것이다[\s\S]*?답변 방식/,
`가장 중요한 원칙은 PDF 리포트 내용을 내부 근거로 삼되, 겉으로는 실제 상담사처럼 자연스럽게 답변하는 것이다

반드시 지켜야 할 규칙

1. 답변은 반드시 제공된 PDF 리포트 내용, 사주 원국 데이터, 챕터 해석을 기준으로 작성한다
2. 하지만 답변에서 "리포트 내용으로 볼 때", "PDF에 따르면", "챕터에서", "리포트 기준으로는", "확인되지 않습니다" 같은 표현을 반복하지 않는다
3. 리포트는 내부 참고 자료로만 사용하고, 내담자에게는 상담사가 직접 풀이해주는 말투로 답한다
4. 질문이 결혼이면 연애운, 결혼운, 배우자궁, 관성/재성, 대운·세운 흐름을 우선 연결해서 답한다
5. 질문이 직업이면 직업운, 재물운, 식상/재성/관성 흐름을 우선 연결해서 답한다
6. 질문이 재물이면 재성, 비겁, 식상, 돈이 들어오고 나가는 방식, 대운·세운 흐름을 우선 연결해서 답한다
7. 질문이 건강이면 오행 균형, 조후, 생활 리듬, 스트레스 반응 중심으로 답한다
8. 리포트에 구체적인 시기가 약하면 "정확히 한 해를 못 박기보다는"처럼 자연스럽게 말하고, 사주 흐름상 강해지는 시기를 부드럽게 짚는다
9. 리포트 내용과 충돌하는 해석은 하지 않는다
10. 대운과 세운은 혼동하지 않는다
11. 현재 연도보다 과거 연도는 과거형으로, 현재 연도는 현재형으로, 미래 연도는 미래형으로 말한다
12. 무섭게 단정하거나 사망, 사고, 질병, 이혼 등을 확정적으로 말하지 않는다
13. 실제 상담처럼 부드럽고 현실적인 존댓말로 답변한다
14. "AI", "데이터상", "모델", "프롬프트", "챕터" 같은 표현은 쓰지 않는다
15. 마침표는 되도록 쓰지 않고 자연스럽게 줄바꿈한다

답변 방식`
);

s = s.replace(
/- 그 다음 PDF 리포트에서 확인되는 근거를 자연스럽게 연결한다/g,
'- 그 다음 사주 근거를 자연스럽게 연결한다'
);

s = s.replace(
/위 PDF 리포트 내용을 반드시 기준으로 삼아 답변하세요/g,
`위 자료는 내부 참고용입니다
겉으로는 절대 리포트 요약처럼 말하지 말고 실제 상담사가 직접 풀이하듯 답변하세요`
);

// 출력 후처리: 리포트봇 표현 제거
if (!s.includes('function cleanConsultAnswer(')) {
  s = s.replace(
    /async function consultAnswer/,
`function cleanConsultAnswer(text) {
  return String(text || '')
    .replace(/리포트 내용으로 볼 때[,，]?/g, '')
    .replace(/PDF 리포트 기준으로는/g, '사주 흐름상')
    .replace(/리포트 기준으로는/g, '사주 흐름상')
    .replace(/이 챕터에서는/g, '이 흐름에서는')
    .replace(/챕터에서/g, '사주 흐름에서')
    .replace(/확인되지 않습니다/g, '단정하기는 어렵습니다')
    .trim();
}

async function consultAnswer`
  );
}

s = s.replace(
  /return text\.trim\(\);/,
  'return cleanConsultAnswer(text);'
);

fs.writeFileSync(file, s, 'utf8');

console.log('made AI chat sound like real consultation');
