const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `[문장 리듬 다양화]`;

const add = `
[현실 행동 디테일 강화]
- 문장을 예쁘게 정리하려고만 하지 마세요.
- 실제 연애에서 튀어나올 법한 행동을 넣으세요.
- "괜찮은 척하지만 계속 확인한다", "말투 하나가 계속 남는다", "답장보다 애매한 반응이 더 오래 남는다" 같은 날것의 장면을 넣으세요.
- 설명보다 행동을 먼저 쓰세요.
- 한 챕터 안에 최소 2개 이상 현실 행동 장면을 넣으세요.

[짧고 강한 문장]
- 각 챕터마다 짧고 강한 문장 2개 이상을 반드시 넣으세요.
- 예: "좋아할수록 더 침착한 척하게 됩니다."
- 예: "확신이 없으면 먼저 다가가지 못합니다."
- 예: "읽씹보다 애매한 답장이 더 오래 남습니다."
- 예: "마음보다 눈치를 먼저 봅니다."
- 예: "괜찮은 척하지만, 사실은 계속 보고 있습니다."

[예측 어려운 리듬]
- 모든 문단을 공감 → 설명 → 조언 순서로 쓰지 마세요.
- 장면 → 짧은 문장 → 감정 반응 → 관계 변화 순서도 사용하세요.
- 혼잣말 같은 문장을 가끔 넣어도 됩니다.
- 예: "왜 이렇게 신경 쓰이지, 하는 순간이 있습니다."
- 예: "괜찮다고 생각했는데, 마음은 아직 남아 있습니다."
- 조언으로 끝내지 말고 감정의 여운으로 끝내세요.

[감정 온도 차별화 강화]
- 썸 챕터는 문장에 두근거림과 애매한 기대감을 넣으세요.
- 질투 챕터는 예민함, 숨기는 불안, 작은 말투 변화에 흔들리는 느낌을 넣으세요.
- 재회 챕터는 미련, 잔상, 다시 흔들리는 분위기를 넣으세요.
- 갈등 챕터는 침묵, 거리감, 차가워지는 말투를 넣으세요.
- 안정기 챕터는 편안함, 신뢰, 오래 가는 관계의 온기를 넣으세요.
`;

if (!s.includes('[현실 행동 디테일 강화]')) {
  s = s.replace(marker, add + '\n' + marker);
}

fs.writeFileSync(file, s, 'utf8');
console.log('enhanced raw emotional rhythm rules');
