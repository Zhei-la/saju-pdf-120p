const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `[추상어 금지 및 행동 장면 전환]`;

const add = `
[반복 성격 설명 제한]
- 아래 표현은 한 챕터 안에서 1회 이상 반복하지 마세요:
  · 신중함
  · 배려형
  · 감정이 깊음
  · 상대 반응에 민감함
  · 혼자 고민함
  · 감정을 숨김
  · 안정감을 중요하게 생각함
- 같은 의미를 다른 말로 반복하지 마세요.
- 성격 설명보다 실제 행동 장면을 우선하세요.

[행동 장면 우선 규칙]
- 추상 설명 대신 실제 행동으로 바꾸세요.

예시:
- "상대 반응에 민감합니다"
→ "답장이 평소보다 짧아지면 괜찮은 척하지만 계속 다시 보게 됩니다"

- "감정을 쉽게 표현하지 않습니다"
→ "좋아할수록 오히려 말수를 줄이고 반응을 더 조심하게 됩니다"

- "생각이 많습니다"
→ "카톡 하나를 보내고도 괜히 말투를 다시 곱씹는 순간이 많습니다"

- "배려심이 많습니다"
→ "서운해도 분위기 망칠까 봐 먼저 참는 쪽에 가깝습니다"

[현실 연애 장면 강제]
- 각 챕터마다 최소 2개 이상 현실 행동 장면을 반드시 넣으세요.
- 아래 장면 중 최소 하나는 포함하세요:
  · 읽씹 확인
  · 답장 텀 신경 씀
  · SNS 다시 보기
  · 말투 변화 눈치챔
  · 먼저 연락할지 고민함
  · 괜찮은 척함
  · 혼자 결론 내림
  · 갑자기 거리 둠
  · 서운하지만 말 안 함

[AI 설명체 억제]
- "~하는 편입니다"
- "~할 수 있습니다"
- "~경향이 있습니다"

같은 문장 끝을 연속 사용하지 마세요.

- 설명문만 이어지지 않게:
  장면 → 짧은 단문 → 감정 반응 → 관계 변화
  흐름을 섞으세요.

[짧은 임팩트 문장]
- 각 챕터마다 짧고 강한 문장 2개 이상 포함:
  · 좋아할수록 더 침착한 척하게 됩니다.
  · 읽씹보다 애매한 답장이 더 오래 남습니다.
  · 확신이 없으면 먼저 다가가지 못합니다.
  · 마음보다 눈치를 먼저 봅니다.
  · 괜찮은 척하지만 사실은 계속 신경 쓰고 있습니다.
`;

if (!s.includes('[반복 성격 설명 제한]')) {
  s = s.replace(marker, marker + '\n' + add);
}

fs.writeFileSync(file, s, 'utf8');
console.log('added anti repetitive personality rules');
