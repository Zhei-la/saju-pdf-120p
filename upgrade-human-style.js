const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

/* =========================
   1. SYSTEM 프롬프트 강화
========================= */

const oldBlock = `상담사가 직접 써준 것처럼 자연스럽고 현실적인 한국어로 작성하세요.
좋은 말만 하지 말고 단점, 조심할 흐름, 실제로 반복될 수 있는 문제도 함께 적어주세요.`;

const newBlock = `상담사가 직접 써준 것처럼 자연스럽고 현실적인 한국어로 작성하세요.
좋은 말만 하지 말고 단점, 조심할 흐름, 실제로 반복될 수 있는 문제도 함께 적어주세요.

절대 사주 이론 설명서처럼 작성하지 마세요.

실제 연애에서 나타나는 행동, 말투, 감정 변화, 연락 방식, 거리감, 질투, 집착, 회피 패턴처럼 현실적인 장면 중심으로 작성하세요.

"수 기운 부족", "신약한 구조", "감정 조절", "안정감", "현실적", "균형" 같은 표현을 반복하지 마세요.

각 챕터마다 완전히 다른 관점과 분위기로 작성하세요.

독자가 "내 이야기 같다"라고 느낄 정도로 구체적으로 묘사하세요.

사주 용어 설명은 최소한으로 줄이고, 실제 사람 상담처럼 자연스럽게 풀어서 설명하세요.

이론 설명보다 실제 관계 흐름과 행동 패턴 묘사를 우선하세요.`;

s = s.replace(oldBlock, newBlock);

/* =========================
   2. 작성지침 강화
========================= */

const oldGuide = `- 같은 용어 해설을 매 챕터 반복하지 말 것`;

const newGuide = `- 같은 용어 해설을 매 챕터 반복하지 말 것
- 같은 사주 용어 반복 금지
- 같은 결론 반복 금지
- 실제 연애 상황 예시 포함
- 연락 패턴, 감정 변화, 관계 흐름 중심으로 작성
- 이론 설명보다 현실 묘사 우선
- 챕터마다 말투와 분위기를 다르게 작성
- 독백형 문체와 상담형 문체를 섞어서 사용
- "수 기운 부족", "신약", "안정감", "현실적", "균형" 반복 금지
- 설명서 말투보다 실제 상담 말투 사용
- 독자가 실제 자기 연애 이야기처럼 느끼게 작성`;

s = s.replace(oldGuide, newGuide);

/* =========================
   3. 용어해설 줄이기
========================= */

s = s.replace(
  /- \[용어 해설\][\s\S]*?반복하지 말 것/g,
  `- [용어 해설]은 정말 필요한 챕터에만 매우 짧게 사용
- 용어 해설 때문에 페이지를 따로 만들지 말 것`
);

/* =========================
   4. 반복 단어 후처리
========================= */

const oldReturn = `return { title, content };`;

const newReturn = `
      content = content
        .replace(/수 기운 부족/g, '감정 기복')
        .replace(/신약한 구조/g, '예민한 성향')
        .replace(/안정감/g, '편안함')
        .replace(/현실적/g, '실질적')
        .replace(/균형/g, '흐름')
        .replace(/조화/g, '호흡');

      return { title, content };`;

s = s.replace(oldReturn, newReturn);

/* =========================
   저장
========================= */

fs.writeFileSync(file, s, 'utf8');

console.log('human-style love report upgraded');
