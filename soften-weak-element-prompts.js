const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

s = s.replace(
  /"단점과 약점을 부족한 오행과 용신을 근거로 1500자 이상\s*분석해주세요\."/g,
  `"단점과 약점을 오행 편중, 십성 구조, 일간 강약, 월령과 조후를 함께 근거로 1500자 이상 분석해주세요. 부족한 오행 하나만으로 단정하지 마세요."`
);

s = s.replace(
  /"건강 취약 부위를 부족한 오행\(목=간, 화=심장, 토=위장,\s*금=폐, 수=신장\)과 12운성을 근거로 1500자 이상 분석해주세요\."/g,
  `"건강 흐름을 오행 편중, 조후, 생활 리듬, 스트레스 반응을 바탕으로 1500자 이상 분석해주세요. 특정 장기나 질병을 단정하지 말고 생활 관리 방향으로 완화해 설명하세요."`
);

s = s.replace(
  /"정신 건강을 신강\/신약 지표와 인성\(정인\/편인\)의 강약을\s*근거로 1500자 이상 분석해주세요\."/g,
  `"정신적 피로와 스트레스 반응을 신강/신약 흐름, 인성 구조, 오행 균형을 함께 근거로 1500자 이상 분석해주세요. 불안이나 질환을 단정하지 말고 감정 관리 방향으로 설명하세요."`
);

fs.writeFileSync(file, s, 'utf8');

console.log('softened weak-element and health prompts');
