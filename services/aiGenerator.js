async function generateChapter(openai, userInfo, title, prompt, index, extraInstruction = '') {
  const ctx = buildContext(userInfo);
  const glossary = getGlossary(index);
  const userMsg = `${ctx}

━━━━━━━━━━━━━━━━━━
분석 항목: ${title}
━━━━━━━━━━━━━━━━━━
${prompt}${extraInstruction ? '\n\n[추가 요청사항]\n' + extraInstruction : ''}

작성 지침:
- 사주 원국 설명은 PART 1 초반에만 사용
- 이후 챕터에서는 행동/심리/관계 흐름 중심으로 작성
- 같은 오행 설명 반복 금지
- 갑목/수기운/신약/식신/편재 반복 금지
- 이론보다 실제 연애 상황을 우선 작성
- 챕터 시작마다 사주 설명 반복 금지
- 이미 설명한 성향 반복 금지
- 각 챕터는 새로운 이야기처럼 구성
- "사주를 보면", "일간이", "오행상" 같은 시작 금지
- "일반적으로 이런 사주는..." 같은 일반론 금지
- 이 사주의 고유한 특징을 정확히 짚어내기
- 1500~2000자 내외, 10만원 퀄리티에 걸맞는 깊이
- 마크다운 기호(#, **, -, 숫자.) 절대 금지
- 첫 문장부터 도입 멘트 없이 바로 본론 ("○○님의 사주를 분석해봤어요" 같은 시작 절대 금지)${glossary ? '\n\n이 챕터의 끝에 아래 용어 해설을 자연스럽게 한 문단 추가:\n' + glossary : ''}`;
  
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await openai.chat.completions.create({
        model: 'gpt-4o',
        temperature: 0.85,
        max_tokens: 2500,
        messages: [
          { role: 'system', content: SYSTEM },
          { role: 'user', content: userMsg }
        ]
      });
      let content = res.choices[0].message.content || '';
      content = content
        .replace(/\*\*/g, '')
        
        .replace(/결론적으로,?/g, '')
        .replace(/AI/g, '')
        .replace(/자동 생성/g, '')

        // 고객을 제3자처럼 부르는 표현 제거
        // 용어해설 반복 제거
        .replace(/\[용어 해설\][\s\S]*$/g, '')

        // 반복되는 사주 용어 완화
        .replace(/갑목\(甲木\)/g, '타고난 성장 기질')
        .replace(/갑목/g, '성장 기질')
        .replace(/신약한 사주/g, '예민하게 반응하는 흐름')
        .replace(/신약한/g, '예민한')
        .replace(/수 기운이 부족/g, '감정 정리가 늦어질 수 있음')
        .replace(/수 기운의 부족/g, '감정 정리가 늦어지는 흐름')
        .replace(/오행 분포/g, '전체 흐름')
        .replace(/사주 원국/g, '기본 흐름')

        // 어색한 변환 보정
        .replace(/호흡로운/g, '조화로운')
        .replace(/불흐름/g, '불안정한 흐름')
        .replace(/예민한 성향로/g, '예민한 성향으로')

        

        // 이름 반복 제거
        // 문단 시작 이름 제거
        // 이름 과다 반복 축소
        // 어색한 표현 제거
        .replace(/성장 기질/g, '갑목')
        .replace(/흐름 있는/g, '안정적인')
        .replace(/흐름잡힌/g, '안정된')
        .replace(/호흡를/g, '조화를')
        .replace(/호흡로운/g, '자연스러운')
        .replace(/불흐름/g, '불안정함')
        .replace(/실질적이고 실질적인/g, '현실적인')
        .replace(/감정의 깊이/g, '감정선')
        .replace(/감정적으로 편안함/g, '심리적 안정감')

        // AI 말투 제거
        .replace(/경향이 있습니다/g, '편입니다')
        .replace(/가능성이 있습니다/g, '수도 있습니다')
        .replace(/필요합니다/g, '중요합니다')
        .replace(/중요합니다 중요합니다/g, '중요합니다')

        // 반복 제거
        .replace(/상대방/g, '상대')

.replace(/상대이/g, '상대가')
        .replace(/호흡를/g, '조화를')
        .replace(/흐름잡힌/g, '안정된')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
      
      content = content
        .replace(/수 기운 부족/g, '감정 기복')
        .replace(/신약한 구조/g, '예민한 성향')
        .replace(/안정감/g, '편안함')
        .replace(/현실적/g, '실질적')
        .replace(/균형/g, '흐름')
        .replace(/조화/g, '호흡');

      return { title, content };
    } catch (err) {
      const msg = err.message || '';
      if (msg.includes('429') || msg.includes('rate limit') || msg.includes('Rate limit')) {
        if (attempt < 2) {
          console.log(`[챕터 ${index}] TPM 초과, 8초 대기 후 재시도...`);
          await new Promise(r => setTimeout(r, 8000));
          continue;
        }
      }
      throw err;
    }
  }
}

