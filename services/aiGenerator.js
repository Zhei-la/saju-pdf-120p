function buildMonthlySections(year) {
  const arr = [];
  for (let m = 1; m <= 12; m++) {
    if (m === 12) {
      arr.push([
        `${year}년 ${m}월 운세 및 종합 조언`,
        `${year}년 ${m}월 운세와 한 해를 마무리하는 종합 조언을 1500자 이상 분석해주세요.`
      ]);
    } else {
      arr.push([
        `${year}년 ${m}월 운세`,
        `${year}년 ${m}월 운세를 해당 월의 월간/월지와 사주 원국의 관계를 근거로 일, 사업, 재물, 건강, 관계로 나누어 1500자 이상 분석해주세요.`
      ]);
    }
  }
  return arr;
}

