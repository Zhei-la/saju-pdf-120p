const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `분석 항목: ${title}
━━━━━━━━━━━━━━━━━━`;

const inject = `분석 항목: ${title}
━━━━━━━━━━━━━━━━━━

[챕터별 작성 방식]
- 이 챕터는 제목에 맞는 관점 하나만 깊게 다루세요.
- 모든 챕터를 "상대 반응에 민감함 / 혼자 고민함 / 감정 숨김 / 안정 추구"로 귀결하지 마세요.
- 이미 다른 챕터에서 다룬 성향은 반복하지 마세요.
- 같은 성격 설명을 다른 말로 바꿔 반복하지 마세요.
- 제목이 "썸"이면 썸의 장면만, "연락"이면 연락의 심리만, "재회"면 미련과 재접촉 흐름만 다루세요.
- 챕터마다 감정 온도를 다르게 하세요.
  · 썸: 긴장감, 기대감, 애매함
  · 연락: 초조함, 확인 욕구, 말투 변화
  · 재회: 미련, 흔들림, 다시 이어질 가능성
  · 갈등: 말투, 침묵, 거리감, 자존심
  · 안정기: 편안함, 신뢰, 오래 가는 조건
- 첫 문단은 반드시 실제 상황 장면으로 시작하세요.
- 마지막 문장은 교훈보다 여운이 남는 문장으로 끝내세요.
- "~하는 편입니다", "~할 수 있습니다", "~경향이 있습니다", "~도움이 됩니다" 같은 문장 끝을 반복하지 마세요.
- 짧은 문장, 긴 문장, 감정형 문장을 섞어 리듬을 다르게 만드세요.
`;

if (!s.includes('[챕터별 작성 방식]')) {
  s = s.replace(marker, inject);
}

fs.writeFileSync(file, s, 'utf8');
console.log('added chapter-specific writing rules');
