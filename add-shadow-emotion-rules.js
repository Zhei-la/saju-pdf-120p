const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `[소름 디테일 강화]`;

const add = `
[불편하지만 현실적인 문장]
- 무조건 좋은 사람처럼만 해석하지 마세요.
- 배려, 신중함, 이해심 같은 표현 뒤에 숨어 있는 불안·회피·예민함도 함께 보여주세요.
- "좋은 말"만 반복하지 말고, 본인도 인정하기 싫어할 현실적인 감정 패턴을 섞으세요.
- 독자가 약간 찔릴 정도의 현실성을 포함하세요.
- 단, 공격적이거나 단정적으로 비난하지는 마세요.

[현실적인 감정 패턴 예시]
- 좋아하는 마음보다 상처받을 가능성을 먼저 계산하는 장면.
- 배려처럼 보이지만 사실은 거절당할 상황을 피하려는 장면.
- 연락이 줄어들면 불안하지만 먼저 표현은 못 하는 장면.
- 상대를 이해하려 하지만 정작 본인 감정은 계속 참는 장면.
- 괜찮은 척하지만 혼자 의미를 곱씹는 장면.
- 마음이 식은 게 아니라 지친 건데, 스스로도 헷갈리는 장면.
- 상대를 믿고 싶지만 작은 변화에도 계속 분위기를 읽게 되는 장면.

[심리 리포트 방향 유지]
- 정통 명리학 설명서처럼 쓰지 마세요.
- "사주 기반 연애 심리 리포트"처럼 읽히게 작성하세요.
- 사주 구조는 근거로만 사용하고, 본문은 현실 감정과 관계 장면 중심으로 풀어내세요.
- 명리 용어를 과하게 늘어놓지 말고 감정 흐름 속에 자연스럽게 녹이세요.
- 독자가 "내 연애 같다"라고 느끼게 만드는 것을 우선하세요.

[좋은 사람 서술 제한]
- "배려심이 많다", "이해심이 많다", "상대를 잘 배려한다" 같은 표현을 반복하지 마세요.
- 대신 그 행동 뒤에 숨어 있는 감정의 이유를 설명하세요.
- 예: "배려라기보다 관계가 틀어지는 상황 자체를 불편해하는 경우가 많습니다."
- 예: "상대를 이해하려 하기보다, 상처받지 않기 위해 먼저 분위기를 읽는 쪽에 가깝습니다."

[감정의 그림자 표현]
- 사람의 밝은 면만 쓰지 말고 그림자도 함께 쓰세요.
- 예민함, 회피, 감정소모, 집착, 혼자 꼬아서 생각하는 부분도 현실적으로 포함하세요.
- 단, 병적으로 보이게 쓰지 말고 누구나 공감 가능한 수준으로 표현하세요.
`;

if (!s.includes('[불편하지만 현실적인 문장]')) {
  s = s.replace(marker, marker + '\n' + add);
}

fs.writeFileSync(file, s, 'utf8');
console.log('added realistic shadow emotion rules');
