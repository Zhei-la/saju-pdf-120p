const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

const marker = `- "혼자 고민", "상대 반응을 신경 씀", "감정 표현이 서툼" 같은 표현은 반복하지 마세요.`;

const add = `
- 같은 핵심 성향을 챕터마다 반복하지 마세요.
- 각 챕터는 반드시 서로 다른 실제 연애 장면으로 시작하세요.
- 챕터마다 아래 장면 중 하나 이상을 구체적으로 포함하세요: 읽씹, 답장 텐션 변화, 썸의 애매함, 싸운 뒤 침묵, 거리두기, 재회 직전, 갑작스러운 연락, 상대 말투 변화.
- 상대 시점에서 이 사람이 어떻게 보일지 1문단 이상 포함하세요.
- 운세형 문장도 반드시 포함하세요: 언제 가까워지는지, 언제 흔들리는지, 언제 연락운이 살아나는지.
- 추상적인 설명 대신 “그 상황에서 실제로 어떤 행동을 하는지”를 적으세요.
- “상대 반응에 민감하다”라고만 쓰지 말고, 어떤 반응에 어떻게 흔들리는지 장면으로 보여주세요.
- “감정을 숨긴다”라고만 쓰지 말고, 말투·답장·거리감이 어떻게 달라지는지 보여주세요.
- “안정감을 원한다”라고만 쓰지 말고, 어떤 사람에게 마음이 열리고 어떤 태도에 닫히는지 설명하세요.
- 각 챕터의 마지막 문장은 조언보다 감정의 여운이 남는 문장으로 마무리하세요.
`;

if (!s.includes('각 챕터는 반드시 서로 다른 실제 연애 장면으로 시작하세요')) {
  s = s.replace(marker, marker + '\n' + add);
}

fs.writeFileSync(file, s, 'utf8');
console.log('strengthened love scene-based prompt');
