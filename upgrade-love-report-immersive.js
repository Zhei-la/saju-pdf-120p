const fs = require('fs');

const file = 'services/aiGenerator.js';
let s = fs.readFileSync(file, 'utf8');

/* =========================
   연애운 프롬프트 강화
========================= */

const oldPrompt = `- 이름 반복 금지`;

const newPrompt = `- 이름 반복 금지
- 분석문/상담문/블로그 스타일 문체를 사용하지 마세요.
- 실제 연애 상황처럼 장면 중심으로 묘사하세요.
- 행동 단위 디테일을 반드시 포함하세요.
- "답장 텐션", "읽씹", "연락 간격", "침착한 척", "혼자 곱씹는 행동" 같은 현실 연애 디테일을 활용하세요.
- 누구에게나 적용되는 추상적 표현보다 실제 행동 묘사를 우선하세요.
- 좋아할수록 나타나는 행동 변화를 구체적으로 설명하세요.
- 상대 입장에서 어떻게 느껴지는지도 포함하세요.
- 감정이 커질수록 어떤 행동을 하는지 묘사하세요.
- 썸, 연락, 거리감, 재회 상황을 실제처럼 설명하세요.
- 설렘, 긴장감, 기대감이 느껴지도록 서술하세요.
- "갑자기 가까워질 가능성", "예상 못한 연락 흐름", "감정이 깊어질 시기" 같은 운세 흐름 표현을 포함하세요.
- 문장 길이를 다양하게 사용하세요.
- "하지만", "중요합니다", "도움이 됩니다", "이러한 경향" 같은 AI형 문체 반복을 줄이세요.`;

/* 기존 규칙 교체 */
if (s.includes(oldPrompt) && !s.includes('답장 텐션')) {
  s = s.replace(oldPrompt, newPrompt);
}

/* =========================
   연애 챕터 구조 개편
========================= */

const oldChaptersRegex = /const loveChapters = \[[\s\S]*?\];/;

const newChapters = `const loveChapters = [
  ["PART 1. 타고난 연애 성향", [
    "사랑에 빠지는 방식",
    "상대가 처음 느끼는 매력",
    "감정 표현 스타일",
    "좋아할수록 나타나는 행동",
    "연애에서 가장 중요하게 생각하는 것"
  ]],

  ["PART 2. 관계 속 행동 패턴", [
    "답장과 연락에 반응하는 방식",
    "썸 단계에서의 심리 흐름",
    "질투와 불안이 올라오는 순간",
    "감정을 숨길 때의 행동",
    "싸우거나 멀어질 때의 반응"
  ]],

  ["PART 3. 현실 연애운 흐름", [
    "연애운이 강해지는 시기",
    "새로운 인연 흐름",
    "재회 가능성 흐름",
    "썸이 깊어질 가능성",
    "감정 변화가 커지는 타이밍"
  ]],

  ["PART 4. 궁합 & 관계 흐름", [
    "잘 맞는 연애 스타일",
    "갈등이 생기기 쉬운 유형",
    "오래 가는 관계 특징",
    "상대 입장에서 보이는 모습",
    "연애 관계 유지 팁"
  ]],

  ["PART 5. 연애운 총정리", [
    "지금 가장 중요한 연애 습관",
    "관계에서 조심해야 할 부분",
    "연애운 상승 포인트",
    "앞으로의 감정 흐름",
    "연애운 핵심 총평"
  ]]
];`;

if (oldChaptersRegex.test(s)) {
  s = s.replace(oldChaptersRegex, newChapters);
}

/* =========================
   AI 문체 후처리 최소 정리
========================= */

if (!s.includes("replace(/이러한 경향/g")) {
  s = s.replace(
    `.replace(/\\s{2,}/g, ' ')`,
    `.replace(/이러한 경향/g, '이런 모습')
        .replace(/도움이 됩니다/g, '좋게 이어질 수 있습니다')
        .replace(/중요합니다/g, '꽤 크게 작용합니다')
        .replace(/하지만 반복/g, '반면')
        .replace(/\\s{2,}/g, ' ')`
  );
}

fs.writeFileSync(file, s, 'utf8');

console.log('upgraded love report structure and immersion prompts');
